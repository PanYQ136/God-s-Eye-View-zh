    "    if (!recentImagery || recentImageryWiring) return;",
    "    recentImagery.attachTileset(tileset);",
    "    const imageryBoxTool = initImageryBoxTool({",
    "      viewer,",
    "      onBox: (box) => recentImagery.setBox(box),",
